function initPreferences() {
  const savedTheme = getStoredPreference("axs-theme", "dark");
  const savedLanguage = getStoredPreference("axs-language", "es");
  const language = savedLanguage === "en" ? "en" : "es";

  applyLanguage(language);
  applyTheme(savedTheme);
  initLanguageToggle(language);
  initThemeToggle(savedTheme);
}

function translate(key, language = getCurrentLanguage()) {
  return key.split(".").reduce((value, part) => value && value[part], translations[language]) || key;
}

function getCurrentLanguage() {
  return document.documentElement.lang === "en" ? "en" : "es";
}

function applyLanguage(language) {
  const selectedLanguage = language === "en" ? "en" : "es";

  document.documentElement.lang = selectedLanguage;
  document.title = translate("ui.title", selectedLanguage);
  setMetaContent('meta[name="description"]', translate("ui.description", selectedLanguage));
  setMetaContent('meta[property="og:title"]', translate("ui.title", selectedLanguage));
  setMetaContent('meta[property="og:description"]', translate("ui.description", selectedLanguage));

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = translate(element.dataset.i18n, selectedLanguage);
  });

  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    element.innerHTML = translate(element.dataset.i18nHtml, selectedLanguage);
  });

  const toggle = document.getElementById("language-toggle");
  if (toggle) {
    const isEnglish = selectedLanguage === "en";
    toggle.setAttribute("aria-pressed", String(isEnglish));
    toggle.setAttribute("aria-label", translate("ui.languageToggle", selectedLanguage));
    const value = toggle.querySelector(".rail-toggle__value");
    if (value) value.textContent = selectedLanguage.toUpperCase();
  }

  updateAccessibleLabels(selectedLanguage);

  setStoredPreference("axs-language", selectedLanguage);

  document.dispatchEvent(new CustomEvent("languagechange", { detail: { language: selectedLanguage } }));
}

function applyTheme(theme) {
  document.body.dataset.theme = theme;
  const toggle = document.getElementById("theme-toggle");
  if (toggle) {
    const isLight = theme === "light";
    toggle.setAttribute("aria-pressed", String(isLight));
    toggle.setAttribute("aria-label", translate(isLight ? "ui.themeToDark" : "ui.themeToLight"));
  }

  setStoredPreference("axs-theme", theme);
}

function setMetaContent(selector, value) {
  const element = document.querySelector(selector);
  if (element) element.setAttribute("content", value);
}

function getStoredPreference(key, fallback) {
  try {
    return localStorage.getItem(key) || fallback;
  } catch (error) {
    return fallback;
  }
}

function setStoredPreference(key, value) {
  try {
    localStorage.setItem(key, value);
  } catch (error) {
    return undefined;
  }
}

function updateAccessibleLabels(language) {
  const labels = [
    [".skip-link", "ui.skip", "textContent"],
    [".navbar", "ui.mainNav", "aria-label"],
    [".navbar__brand", "ui.brandHome", "aria-label"],
    ["#menu-toggle", "ui.openMenu", "aria-label"],
    [".accessibility-rail", "ui.preferences", "aria-label"],
    [".logo-marquee", "ui.companiesCarousel", "aria-label"],
    [".footer__nav", "ui.footerNav", "aria-label"]
  ];

  labels.forEach(([selector, key, attribute]) => {
    const element = document.querySelector(selector);
    if (!element) return;
    const value = translate(key, language);
    if (attribute === "textContent") element.textContent = value;
    else element.setAttribute(attribute, value);
  });

  const themeToggle = document.getElementById("theme-toggle");
  if (themeToggle) {
    const key = document.body.dataset.theme === "light" ? "ui.themeToDark" : "ui.themeToLight";
    themeToggle.setAttribute("aria-label", translate(key, language));
  }
}

function initLanguageToggle(language) {
  const toggle = document.getElementById("language-toggle");
  if (!toggle) return;

  toggle.addEventListener("click", () => {
    applyLanguage(getCurrentLanguage() === "es" ? "en" : "es");
  });

  toggle.setAttribute("aria-pressed", String(language === "en"));
}

function initThemeToggle(theme) {
  const toggle = document.getElementById("theme-toggle");
  if (!toggle) return;

  toggle.addEventListener("click", () => {
    applyTheme(document.body.dataset.theme === "dark" ? "light" : "dark");
  });

  toggle.setAttribute("aria-pressed", String(theme === "light"));
}

window.AXS = {
  initPreferences,
  translate,
  applyLanguage,
  applyTheme
};
